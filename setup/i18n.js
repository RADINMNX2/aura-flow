const DICT = { en: EN, fa: FA };
let lang = "en";
const hooks = new Set();
const KEY = "flow-setup.lang.v1";

export const t = (key, vars) => {
  const raw = DICT[lang]?.[key] ?? EN[key] ?? key;
  return vars ? raw.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m)) : raw;
};
export const getLang = () => lang;
export const meta = (l = lang) => (l === "fa" ? { dir: "rtl", label: "FA" } : { dir: "ltr", label: "EN" });
export const onLang = (fn) => { hooks.add(fn); return () => hooks.delete(fn); };

export function initI18n() {
  let stored = null;
  try { stored = localStorage.getItem(KEY); } catch {}
  const auto = (navigator.language || "").toLowerCase().startsWith("fa") ? "fa" : "en";
  lang = stored === "fa" || stored === "en" ? stored : auto;
  applyDom();
  sync();
  return lang;
}

export function setLang(next) {
  if (next !== "en" && next !== "fa") return;
  lang = next;
  try { localStorage.setItem(KEY, lang); } catch {}
  applyDom();
  sync();
  hooks.forEach((fn) => { try { fn(lang); } catch (e) { console.error(e); } });
  document.documentElement.classList.add("is-lang-swap");
  setTimeout(() => document.documentElement.classList.remove("is-lang-swap"), 320);
}

export function toggleLang() { setLang(lang === "en" ? "fa" : "en"); }

function sync() {
  const m = meta();
  document.documentElement.lang = lang;
  document.documentElement.dir = m.dir;
  const cur = document.querySelector("#lang-cur");
  if (cur) cur.textContent = m.label;
  const btn = document.querySelector("#lang-btn");
  if (btn) btn.setAttribute("aria-label", t("chrome.lang"));
  document.title = t("setup.title");
}

export function applyDom(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((n) => { const v = t(n.dataset.i18n); if (n.textContent !== v) n.textContent = v; });
  root.querySelectorAll("[data-i18n-html]").forEach((n) => { const v = t(n.dataset.i18nHtml); if (n.innerHTML !== v) n.innerHTML = v; });
  root.querySelectorAll("[data-i18n-aria]").forEach((n) => { const v = t(n.dataset.i18nAria); if (n.getAttribute("aria-label") !== v) n.setAttribute("aria-label", v); });
}
