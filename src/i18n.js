const DICT = { en: EN, fa: FA };
const META = {
  en: { dir: "ltr", label: "EN", name: "English" },
  fa: { dir: "rtl", label: "FA", name: "فارسی" },
};

let lang = "en";
const hooks = new Set();
const STORE_KEY = "aura-flow.lang.v1";

export const t = (key, vars) => {
  const raw = DICT[lang]?.[key] ?? EN[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m));
};

export const getLang = () => lang;
export const isRTL = () => lang === "fa";
export const langMeta = (l = lang) => META[l] || META.en;
export const nextLang = () => (lang === "en" ? "fa" : "en");

// Modules register here and get called whenever the language changes. They re-render
// computed text (hints, badges, summaries) that data-i18n cannot reach.
export function onLang(fn) {
  hooks.add(fn);
  return () => hooks.delete(fn);
}

export function initI18n() {
  let stored = null;
  try { stored = localStorage.getItem(STORE_KEY); } catch { /* private mode */ }
  const auto = (navigator.language || "").toLowerCase().startsWith("fa") ? "fa" : "en";
  lang = stored === "fa" || stored === "en" ? stored : auto;
  applyDom();
  syncChrome();
  return lang;
}

export function setLang(next, { silent = false } = {}) {
  if (next !== "en" && next !== "fa") return;
  lang = next;
  try { localStorage.setItem(STORE_KEY, lang); } catch { /* ignore */ }
  applyDom();
  syncChrome();
  document.documentElement.classList.add("is-lang-swap");
  setTimeout(() => document.documentElement.classList.remove("is-lang-swap"), 320);
  if (!silent) hooks.forEach((fn) => { try { fn(lang); } catch (e) { console.error(e); } });
  dispatchEvent(new CustomEvent("flow:lang", { detail: { lang } }));
}

export function toggleLang() { setLang(nextLang()); }

function syncChrome() {
  const html = document.documentElement;
  html.lang = lang;
  html.dir = langMeta().dir;
  const cur = $("#lang-cur");
  if (cur) cur.textContent = langMeta().label;
  const btn = $("#btn-lang");
  if (btn) {
    btn.setAttribute("aria-label", lang === "en" ? "Switch language to Persian" : "تغییر زبان به انگلیسی");
    btn.dataset.tip = t("tip.lang");
  }
  document.title = t("app.title");
}

// Static markup carries data-i18n / data-i18n-html / data-i18n-tip / data-i18n-aria /
// data-i18n-placeholder. One pass translates everything, including freshly built nodes.
export function applyDom(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((n) => {
    const v = t(n.dataset.i18n);
    if (n.textContent !== v) n.textContent = v;
  });
  root.querySelectorAll("[data-i18n-html]").forEach((n) => {
    const v = t(n.dataset.i18nHtml);
    if (n.innerHTML !== v) n.innerHTML = v;
  });
  root.querySelectorAll("[data-i18n-tip]").forEach((n) => {
    const v = t(n.dataset.i18nTip);
    if (n.dataset.tip !== v) n.dataset.tip = v;
  });
  root.querySelectorAll("[data-i18n-aria]").forEach((n) => {
    const v = t(n.dataset.i18nAria);
    if (n.getAttribute("aria-label") !== v) n.setAttribute("aria-label", v);
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((n) => {
    const v = t(n.dataset.i18nPlaceholder);
    if (n.getAttribute("placeholder") !== v) n.setAttribute("placeholder", v);
  });
}
